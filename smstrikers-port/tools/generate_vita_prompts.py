#!/usr/bin/env python3
"""Bake the four existing CC0 PlayStation face icons for native Vita prompts.

This is an offline asset tool; the Vita has no PNG/SDL dependency. Resampling
uses an exact integer area average of premultiplied RGBA, then converts back to
straight RGBA. No color quantization or palette is introduced.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

NAMES = ("cross", "circle", "square", "triangle")
SIZE = 28


def sha(data):
    return hashlib.sha256(data).hexdigest()


def rounded(num, den):
    return (num * 2 + den) // (den * 2)


def reduce_icon(image):
    image = image.convert("RGBA")
    bounds = image.getchannel("A").getbbox()
    if bounds is None:
        raise ValueError("An empty icon is not a usable prompt")
    image = image.crop(bounds)
    if image.width != image.height:
        raise ValueError("Expected square face icons; review layout before changing art")
    w, h = image.size
    source = image.tobytes()
    pixels = bytearray(SIZE * SIZE * 4)
    for y in range(SIZE):
        for x in range(SIZE):
            accum = [0, 0, 0, 0]
            for sy in range(y * h // SIZE, ((y + 1) * h + SIZE - 1) // SIZE):
                wy = max(0, min((y + 1) * h, (sy + 1) * SIZE) - max(y * h, sy * SIZE))
                for sx in range(x * w // SIZE, ((x + 1) * w + SIZE - 1) // SIZE):
                    wx = max(0, min((x + 1) * w, (sx + 1) * SIZE) - max(x * w, sx * SIZE))
                    off = (sy * w + sx) * 4
                    a = source[off + 3] * wx * wy
                    for c in range(3):
                        accum[c] += source[off + c] * a
                    accum[3] += a
            out = (y * SIZE + x) * 4
            pixels[out + 3] = rounded(accum[3], w * h)
            if pixels[out + 3] and accum[3]:
                for c in range(3):
                    pixels[out + c] = rounded(accum[c], accum[3])
    return bytes(pixels), bounds


def generate(assets, output):
    records = []
    images = []
    for name in NAMES:
        relative = Path("kenney/PlayStation Series") / ("playstation_button_color_" + name + ".png")
        path = assets / relative
        original = path.read_bytes()
        with Image.open(path) as image:
            original_size = list(image.size)
            pixels, crop = reduce_icon(image)
        records.append(dict(name=name, path=str(relative), png_sha256=sha(original),
                            png_bytes=len(original), original_size=original_size,
                            alpha_crop=list(crop), rgba_sha256=sha(pixels),
                            width=SIZE, height=SIZE, rgba_bytes=len(pixels)))
        images.append(pixels)
    license_bytes = (assets / "LICENSE-Kenney.txt").read_bytes()
    header = [
        "// Generated by tools/generate_vita_prompts.py; do not hand-edit pixels.",
        "// Art: Kenney Input Prompts 1.5A, CC0-1.0.",
        "// License: assets/input-prompts/LICENSE-Kenney.txt",
        "// SPDX-License-Identifier: CC0-1.0",
        "#pragma once", "#include <cstdint>", "",
        "namespace vita_prompt_art {",
        "constexpr unsigned kSide = 28;",
        "constexpr unsigned kCount = 4;",
        "constexpr std::uint8_t kPixels[kCount][kSide * kSide * 4] = {"
    ]
    for record, pixels in zip(records, images):
        header.append("    // " + record["name"] + "; original PNG SHA-256 " + record["png_sha256"])
        header.append("    {")
        for at in range(0, len(pixels), 24):
            header.append("        " + ", ".join(f"0x{x:02x}" for x in pixels[at:at + 24]) + ",")
        header.append("    },")
    header += ["};", "} // namespace vita_prompt_art", ""]
    data = "\n".join(header).encode()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(data)
    return dict(schema="strikers-vita-prompt-art-v1", generator_sha256=sha(Path(__file__).read_bytes()),
                art_license="CC0-1.0", license_sha256=sha(license_bytes),
                sampler="integer area average of premultiplied RGBA; round half up",
                output_header=str(output), output_sha256=sha(data), icons=records)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    args = parser.parse_args()
    report = generate(args.assets, args.output)
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"icons": len(report["icons"]), "header_sha256": report["output_sha256"],
                      "pixel_bytes": sum(x["rgba_bytes"] for x in report["icons"])}))


if __name__ == "__main__":
    main()
